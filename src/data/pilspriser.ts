/** Beskriver tilbudsprisen som «Før/etter kl. …» i stedet for «happy hour». */
export function tilbudstekst(s: Pilssted): string | null {
  if (!s.tilbud) return null;
  const dager = s.tilbudDager.length ? ` (${s.tilbudDager.join(", ")})` : "";
  if (s.tilbudSlutt) return `Pris før kl. ${s.tilbudSlutt}${dager}`;
  if (s.tilbudStart) return `Pris etter kl. ${s.tilbudStart}${dager}`;
  return `Tilbudspris deler av døgnet${dager}`;
}

